/**
 * Lightweight runtime localization. Chinese is the authored source string and the dictionary key;
 * dynamic strings are handled by the regex rules below. Switching the language only flips a
 * snapshot state, so every visible Text recomposes without a resource rebuild.
 */
object Loc {
    var english by mutableStateOf(false)
        private set

    fun applyEnglish(value: Boolean) {
        english = value
    }

    fun t(source: String): String {
        if (!english) return source
        En[source]?.let { return it }
        for ((pattern, replacement) in Rules) {
            val match = pattern.matchEntire(source) ?: continue
            return pattern.replace(source) { m ->
                var result = replacement
                for (i in 1..m.groupValues.lastIndex) {
                    result = result.replace("{$i}", m.groupValues[i])
                }
                result
            }
        }
        return source
    }

